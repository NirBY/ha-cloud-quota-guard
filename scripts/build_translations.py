"""Bundle the shared Hebrew catalog into the standalone Lovelace card."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
base = ROOT / "custom_components/quota_guard"
catalog = json.loads((base / "languages/he.json").read_text(encoding="utf-8"))
card = base / "frontend/quota-guard-card.js"
source = card.read_text(encoding="utf-8")
marker = "// END GENERATED TRANSLATIONS\n"
if marker in source:
    source = source.split(marker, 1)[1]
legacy = {value: key for key, value in catalog.items()}
version = json.loads((base / "manifest.json").read_text(encoding="utf-8"))["version"]
header = "// Generated by scripts/build_translations.py from manifest.json and languages/he.json.\n"
header += "const CARD_VERSION=" + json.dumps(version) + ";\n"
header += (
    "const HE_TEXT="
    + json.dumps(catalog, ensure_ascii=False, separators=(",", ":"))
    + ";\n"
)
header += (
    "const LEGACY_TEXT="
    + json.dumps(legacy, ensure_ascii=False, separators=(",", ":"))
    + ";\n"
)
card.write_text(header + marker + source, encoding="utf-8")
